      + '\n  - 情境区分：选项对应剧情里真实存在的不同走向。例：路口——「向左走（去市场）」「向右走（回客栈）」；面对敌人——「正面硬刚」「绕后偷袭」「转身就跑」。不同选项把故事引向不同事件 / 地点 / 后果。'
      + '\n  - 价值区分：选项代表人物不同的立场、态度、判断。例：与人对峙——「赞同对方」「反对对方」「冷眼分析现实」；是否揭穿谎言——「当场拆穿」「将计就计」「沉默旁观」。选项体现人物的价值观与抉择，带来不同的关系走向与后续冲突。'
      + '\n·【严禁】写与当前剧情、人物、情境毫无关联、且彼此没有价值区别的选项。反例（错误）：「跑着走」「跳着走」「用走的」——这只是移动方式的措辞差异，不改剧情走向、不体现任何人物抉择，玩家选哪个体验完全相同，是无效选项；又如「说好话」「说坏话」若无具体情境支撑也只是同义反复。'
      + '\n·【简单对话分支（快速回主线）】若是轻松对话、用户只想要几个简单分支并很快回到主对话，选项可用「情绪态度」区分——同一意思用不同语气 / 态度回应，玩家体验的是「我以什么姿态面对对方」而非「剧情走哪边」。例：对方讲了个冷笑话——「调侃地回怼」「平淡地敷衍」「真诚地陪笑」。这类分支块可很短（几句回应 + 立刻 <跳回>），不必展开长剧情。'
      + '\n· 自检：写出每个选项后问自己——「选 A 与选 B，玩家会体验到不同的事件、不同的关系变化、或不同的自己吗？」若不会，就改写或删掉该选项。'
      + '\n·【反例对照（务必避免错误写法）】'
      + '\n  错误：<选项:"跑着走",A><选项:"跳着走",B>  （移动方式 ≠ 剧情抉择，无价值区分）'
      + '\n  错误：<选项:"大声说",A><选项:"小声说",B>  （仅音量差异，无情节 / 价值后果）'
      + '\n  正确：<选项:"把真相告诉他",坦白><选项:"继续隐瞒",隐瞒>  （价值观 / 关系走向不同）'
      + '\n  正确：<选项:"接过他的酒一饮而尽",豪爽><选项:"欠身谢过却不沾杯",疏离>  （态度与关系距离不同）'
