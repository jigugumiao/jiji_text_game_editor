  // ---------- 修饰符剥离（提取线索时，把演出标记去掉以节省 token，仅留叙事文本） ----------
  function stripDecorators(text) {
    if (!text) return '';
    let t = String(text);
    // 1) 去双尖括号块定义（<<剧情块:...>> / <<对话块:...>>）
    t = t.replace(/<<[^>]*>>/g, ' ');
    // 2) 去单尖括号整行指令（<...>），如 <召唤物品:宝箱> / <停顿>
    t = t.replace(/<[^>]*>/g, ' ');
    // 3) 去除方括号 BBCode 标签（开/闭都去，保留包裹的纯文本，如 [b]那把伞[/b] → 那把伞）
    t = t.replace(/\[[^\]]*\]/g, '');
    // 4) 变量 {名} 保留内部名字（{金币} → 金币），便于线索分析识别变量
    t = t.replace(/\{([^}]*)\}/g, '$1');
    // 5) 删除整行注释（// 开头，属作者元备注、非正文）
    t = t.split('\n').filter(l => !/^\s*\/\//.test(l)).join('\n');
    // 6) 压缩多余空行、行尾空白
    t = t.replace(/\n{3,}/g, '\n\n').replace(/[ \t]+\n/g, '\n').trim();
    return t;
  }

