  // 依据创作设定判断是否为悬疑 / 恐怖（关键词命中即视为，从而自动启用可感性理论）
  function detectHorrorSuspense(creation) {
    const c = creation || {};
    const text = [c.outline, c.intro, c.world, c.style].filter(Boolean).join('\n');
    if (!text) return false;
    const keys = ['恐怖', '惊悚', '悬疑', '诡异', '灵异', '怪谈', '克苏鲁', '鬼故事', '恐怖故事', '悬疑小说', '心理惊悚',
      'horror', 'suspense', 'thriller', 'creepy', 'scary', 'ghost', 'supernatural', 'eerie', 'psychological thriller'];
    const low = text.toLowerCase();
    return keys.some(k => low.indexOf(k.toLowerCase()) !== -1);
  }

