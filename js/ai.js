  // ---------- 解析输出：剥 ``` 代码块 + 归一化换行 ----------
  function parseOutput(s) {
    if (!s) return '';
    let t = String(s).replace(/\r\n/g, '\n').trim();
    const fence = t.match(/^```(?:[a-zA-Z0-9_-]*)?\n?([\s\S]*?)```$/);
    if (fence) t = fence[1].trim();
    t = t.replace(/```/g, '');
    // 归一化换行：剧本格式为「一行一句、逐行拼接」，句间严禁空行；
    // 模型常误用双回车分隔句子/段落，这里把连续 2+ 换行压成单个换行
    // （场景 / 段落转换请改用 <分割线:>，不要用空行）。
    t = t.replace(/\n{2,}/g, '\n');
    return t;
  }

  // ---------- 解析输出：分离「需求素材」待办清单 ----------
  // 返回 { story, requirements }。requirements 为 <需求素材>…</需求素材> 区块内的纯文本（已 trim），无则为空串。
  // story 为已剔除该区块、可直接插入剧本的正文。
  function splitRequirements(raw) {
    if (!raw) return { story: raw || '', requirements: '' };
    const m = raw.match(/<需求素材>([\s\S]*?)<\/需求素材>/);
    if (!m) return { story: raw.trim(), requirements: '' };
    const requirements = m[1].replace(/^\s*\n/, '').replace(/\n\s*$/, '').trim();
    const story = (raw.slice(0, m.index) + raw.slice(m.index + m[0].length)).trim();
    return { story, requirements };
  }

  // ---------- 解析输出：拆分「6 个开头钩子」 ----------
  // 兼容 AI 的两种输出格式：
  //   A) 严格成对标签：【钩子1】…【/钩子1】…【钩子6】…【/钩子6】
  //   B) 仅开头标签（最常见）：【钩子1】…【钩子2】…【钩子6】（无结尾标签）
  // 返回抽取出的字符串数组（已 trim，按数字顺序，最多 6 个）。
  // 若标签未命中，则用数字标题（1. / 第1个 / 钩子1：）做兜底切分；仍不行则整段作为单个返回。
  function splitHooks(raw) {
    if (!raw) return [];
    const t = parseOutput(raw);
    if (!t.trim()) return [];

    // ---- 方式 A：严格成对标签（优先，最精确）----
    const rePair = /【钩子\s*(\d+)\s*】([\s\S]*?)【\s*\/\s*钩子\s*\1\s*】/g;
    const pairMap = {};
    let mp;
    while ((mp = rePair.exec(t)) !== null) {
      const idx = parseInt(mp[1], 10);
      if (idx >= 1 && idx <= 6) pairMap[idx] = mp[2].trim();
    }
    const pairArr = [];
    for (let i = 1; i <= 6; i++) if (pairMap[i]) pairArr.push(pairMap[i]);
    if (pairArr.length >= 2) return pairArr.slice(0, 6);

    // ---- 方式 B：仅开头标签，按下一个【钩子…】或【/钩子…】切开（兼容无结尾标签）----
    const openRe = /【\s*钩子\s*(\d+)\s*】/g;
    const positions = [];
    let mo;
    while ((mo = openRe.exec(t)) !== null) {
      positions.push({ idx: parseInt(mo[1], 10), contentStart: mo.index + mo[0].length });
    }
    if (positions.length >= 2) {
      const anyRe = /【\s*(?:\/)?\s*钩子\s*\d+\s*】/g;
      const openMap = {};
      for (let i = 0; i < positions.length; i++) {
        const p = positions[i];
        anyRe.lastIndex = p.contentStart;
        const nx = anyRe.exec(t);
        const end = (nx && nx.index >= p.contentStart) ? nx.index : t.length;
        openMap[p.idx] = t.slice(p.contentStart, end).trim();
      }
      const openArr = [];
      for (let i = 1; i <= 6; i++) if (openMap[i]) openArr.push(openMap[i]);
      if (openArr.length >= 2) return openArr.slice(0, 6);
    }

    // ---- 兜底：按数字标题切分（1. / 第N个 / 钩子N： 等）----
    const segs = t.split(/\n\s*(?:#{1,4}\s*)?(?:第?\s*\d+\s*[.、:：]|钩子\s*\d+\s*[:：])\s*/)
      .map(s => s.trim()).filter(Boolean);
    if (segs.length >= 2) return segs.slice(0, 6);
    return [t.trim()];
  }

  // ---------- 解析输出：把一次性产出的多块剧本拆成「主剧情 + 分支块」 ----------
  // AI 用独占一行的「<<剧情块:块名>>」（双尖括号）标记一个分支块的开始；
  // 其后内容属于该块，直到下一个「<<剧情块:...>>」或文本结束；块以「<跳回>」/<跳回重选> 收尾回到父块。
  // 返回 { main: 主剧情文本(移除 <<>> 定义标记后、保留块前原文与 <跳回> 后的续写), blocks: { 块名: 文本 } }。
  // 注意：抽出块后【不再】往 main 里补 <剧情块:名> 无条件跳转指令——分支一律由 <选项:"…",名> 负责到达；
  // 单尖括号 <剧情块:名> 是无条件跳转指令（较少用），误插会覆盖玩家的选择、导致分支被强制重看。
  // 若输出不含任何 <<剧情块:...>>，则 main=整段、blocks={}（向下兼容「单块」写法）。
  function splitIntoBlocks(raw) {
    if (!raw) return { main: '', blocks: {} };
    const DELIM = /^\s*<<(?:对话块|剧情块):\s*([^>\n]+?)\s*>>\s*$/;
    const isDelim = (l) => { const m = l.match(DELIM); return m ? m[1].trim() : null; };
    const isReturn = (l) => /^\s*<(?:跳回|跳回重选)>\s*$/.test(l);
    function parseScope(text) {
      const lines = text.split('\n');
      let parent = '';
      const scopeBlocks = {};
      let i = 0;
      while (i < lines.length) {
        const name = isDelim(lines[i]);
        if (name) {
          const childLines = [];
          const contLines = [];
          let j = i + 1;
          let closed = false;
          let depth = 0;   // 嵌套块深度：遇 <<剧情块:>> 加深，遇 <跳回>/<跳回重选> 减浅
          while (j < lines.length) {
            if (isDelim(lines[j])) { depth++; childLines.push(lines[j]); j++; continue; }
            if (isReturn(lines[j])) {
              if (depth === 0) { childLines.push(lines[j]); closed = true; j++; break; } // 本块的 <跳回>
              depth--; childLines.push(lines[j]); j++; continue;                          // 嵌套块的 <跳回>，留在 childLines 内由递归处理
            }
            childLines.push(lines[j]); j++;
          }
          if (closed) {                                    // <跳回> 之后的内容回到父块（同级续写）
            while (j < lines.length) {
              if (isDelim(lines[j])) break;
              contLines.push(lines[j]); j++;
            }
          }
          const child = parseScope(childLines.join('\n'));  // 递归处理嵌套块
          // 子块若没以 <跳回>/<跳回重选> 收尾，补一个 <跳回>，保证运行时能返回父块
          let childText = child.text;
          const ct = childText.replace(/\s+$/, '');
          if (ct && !ct.endsWith('<跳回>') && !ct.endsWith('<跳回重选>')) childText = ct + '\n<跳回>';
          else childText = ct;
          scopeBlocks[name] = childText;
          Object.assign(scopeBlocks, child.blocks);
          if (contLines.length) parent += contLines.join('\n') + (contLines[contLines.length - 1].trim() ? '\n' : '');
          i = j;
          continue;
        }
        parent += lines[i] + '\n';
        i++;
      }
      const cleaned = parent.replace(/\n{3,}/g, '\n\n').replace(/[ \t]+\n/g, '\n').replace(/\s+$/, '');
      return { text: cleaned, blocks: scopeBlocks };
    }
    const r = parseScope(raw);
    return { main: r.text, blocks: r.blocks };
  }

  // ---------- 错误友好化 & 瞬时错误重试辅助 ----------
  function sleep(ms) { return new Promise(r => setTimeout(r, ms)); }
  function isTransientError(status, rawMsg) {
    if (status >= 500) return true;
    if (status === 429) return true; // 限流
    const m = (rawMsg || '').toLowerCase();
    return /overload|server (is )?busy|rate limit|too many requests|try again|service unavailable|gateway|timeout/i.test(m);
  }
  function friendlyApiError(status, rawMsg, retrying) {
    const rm = (rawMsg || '').toLowerCase();
    if (status === 401 || status === 403)
      return 'API Key 无效或无权限（HTTP ' + status + '）。请到 AI 设置检查 Key 是否正确、是否已开通该模型的调用权限。';
    if (status === 429 || /rate limit|too many requests/i.test(rm))
      return '请求过于频繁，触发了接口限流（429）。请稍候几十秒再试一次。';
    if (status === 400 || status === 422)
      return '请求参数有误（HTTP ' + status + '）' + (rawMsg ? '：' + rawMsg : '') + '。若反复出现请反馈。';
    if (status >= 500 || /overload|busy|service|try again|timeout|gateway/i.test(rm)) {
      const tail = retrying ? '已自动重试仍失败，' : '';
      return '大模型服务暂时繁忙（服务端过载' + (status ? '，HTTP ' + status : '') + '）。' + tail + '请稍候几秒再试，持续出现通常是平台高峰期。';
    }
    return '调用大模型出错（HTTP ' + status + '）' + (rawMsg ? '：' + rawMsg : '') + '。';
  }

  // ---------- 调用 Deepseek（支持 SSE 流式，含瞬时错误自动重试） ----------
  async function callDeepseek(messages, opts) {
    opts = opts || {};
    const s = loadSettings();
    s.key = (s.key || '').trim();
    s.base = (s.base || '').trim() || DEFAULT_BASE;
    if (!s.key) throw new Error('未配置 Deepseek API Key（在 AI 抽屉的设置里填写）');
    // fetch 要求 header 值必须是 ISO-8859-1（Latin-1）；若 Key/地址里混入中文或全角符号，
    // 浏览器会在构造请求时抛晦涩的 "Failed to read the 'headers' property"，这里提前给出明确提示
    if (/[^\x00-\xFF]/.test(s.key)) {
      throw new Error('API Key 含有非法字符（复制时可能混入了中文或全角符号，如全角字母/全角空格）。请打开 AI 设置，把 Key 整段删掉、重新粘贴纯英文/数字/符号的 Key 后重试。');
    }
    if (/[^\x00-\xFF]/.test(s.base)) {
      throw new Error('API 地址含有非法字符（可能混入了中文或全角符号）。请检查地址格式，应为 https:// 开头的纯英文地址。');
    }
    const url = (s.base || DEFAULT_BASE).replace(/\/+$/, '') + '/chat/completions';
    const body = {
      model: s.model || DEFAULT_MODEL,
      messages: messages,
      temperature: (typeof s.temp === 'number' && !isNaN(s.temp)) ? s.temp : 0.8,
      // 必须显式给 max_tokens：思考模式的 reasoning_content 计入输出额度，不设会被服务端默认上限截断（“写一半断了”）。
      // 从大纲生成（thinking）给足 32768：冗长推理链 + 长正文初稿都能容纳，单次生成可稳定持续约 3 分钟不截断；
      // 轻活（非 thinking）沿用 8192 即可（输出短、无需为上限多烧 token）。
      max_tokens: opts.thinking ? 32768 : 8192,
      stream: !!opts.stream,
    };
    // 思考模式（Deepseek V4）：thinking 必须是对象 { type: 'enabled'/'disabled' }，
    // 传 boolean true 会被服务端以 "expected struct ThinkingOptions" 拒绝。
    // 注意 V4 默认 thinking=enabled，故轻活模式需显式 disabled，避免被默认思考拖慢、多烧 token。
    if (opts.thinking) {
      body.thinking = { type: 'enabled' };
      body.reasoning_effort = 'high';
    } else {
      body.thinking = { type: 'disabled' };
    }
    // 瞬时错误（服务端过载 5xx / 限流 429 / 网络抖动）自动重试：503 这类 “Server Overloaded” 多数重试一次即成功
    const MAX_RETRY = 2;
    let lastErr = null;
    for (let attempt = 0; attempt <= MAX_RETRY; attempt++) {
      if (attempt > 0) await sleep(1500 * attempt); // 指数退避：第 1 次失败后 1.5s，第 2 次失败后 3s
      let res;
      try {
        res = await fetch(url, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json', 'Authorization': 'Bearer ' + s.key },
          body: JSON.stringify(body),
          signal: opts.signal || null,
        });
      } catch (netErr) {
        if (netErr && netErr.name === 'AbortError') throw netErr; // 用户主动取消，不重试
        lastErr = new Error('网络请求失败：' + (netErr && netErr.message ? netErr.message : String(netErr)) + '。请检查网络连接后重试。');
        if (attempt < MAX_RETRY) continue;
        throw lastErr;
      }
      if (!res.ok) {
        let rawMsg = '';
        try { const j = await res.json(); if (j && j.error && j.error.message) rawMsg = j.error.message; } catch (e) {}
        if (isTransientError(res.status, rawMsg) && attempt < MAX_RETRY) {
          lastErr = new Error(friendlyApiError(res.status, rawMsg, true));
          if (opts.onStatus) opts.onStatus('大模型服务繁忙，正在自动重试（' + (attempt + 1) + '/' + MAX_RETRY + '）…');
          continue;
        }
        throw new Error(friendlyApiError(res.status, rawMsg, false));
      }
      // finish_reason === 'length' 表示被 max_tokens 截断（“半截就没了”），记到 opts 上供上层自动续写补全
      if (opts) opts._finishReason = null;
    if (!opts.stream) {
      const j = await res.json();
      if (opts && j.choices && j.choices[0]) opts._finishReason = j.choices[0].finish_reason || null;
      return (j.choices && j.choices[0] && j.choices[0].message && j.choices[0].message.content) || '';
    }
    // 若服务端未真正流式（某些 OpenAI 兼容中转会忽略 stream、返回单块 JSON），按 JSON 解析，避免内容丢失变成空
    const ct = (res.headers && res.headers.get) ? res.headers.get('content-type') : '';
    if ((!ct || ct.indexOf('text/event-stream') === -1) && typeof res.json === 'function') {
      try {
        const j = await res.json();
        if (opts && j.choices && j.choices[0]) opts._finishReason = j.choices[0].finish_reason || null;
        return (j.choices && j.choices[0] && j.choices[0].message && j.choices[0].message.content) || '';
      } catch (e) { /* 解析失败则继续按 SSE 处理 */ }
    }
    // SSE 解析
    const reader = res.body.getReader();
    const decoder = new TextDecoder();
    let buf = '';
    let full = '';
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      buf += decoder.decode(value, { stream: true });
      const parts = buf.split('\n');
      buf = parts.pop();
      for (const line of parts) {
        const t = line.trim();
        if (!t || t.indexOf('data:') !== 0) continue;
        const data = t.slice(5).trim();
        if (data === '[DONE]') continue;
        try {
          const j = JSON.parse(data);
          const delta = j.choices && j.choices[0] && j.choices[0].delta && j.choices[0].delta.content;
          if (delta) { full += delta; if (opts.onToken) opts.onToken(delta, full); }
          const fr = j.choices && j.choices[0] && j.choices[0].finish_reason;
          if (fr && opts) opts._finishReason = fr;
        } catch (e) { /* 忽略不完整片段 */ }
      }
    }
      return full;
    } // end retry loop
    throw lastErr || new Error('请求失败，请重试');
  }

  // ---------- 编排主循环 ----------
  // opts: { mode, ctx, reviseNote, onToken, onStatus, signal }
  async function orchestrate(opts) {
    const mode = opts.mode;
    const ctx = opts.ctx;
    const s = loadSettings();
    if (opts.onStatus) opts.onStatus('组装上下文');
    const projectMode = getMode();
    const horrorSuspense = detectHorrorSuspense(ctx && ctx.creation);
    const forcePlain = projectMode === 'article'; // 通用文章：不写分支 / 谜题
    const puzzle = forcePlain ? 0 : ((typeof opts.puzzle === 'number' && !isNaN(opts.puzzle)) ? opts.puzzle : 0);
    const branches = forcePlain ? 0 : ((typeof opts.branches === 'number' && !isNaN(opts.branches)) ? opts.branches : 0);
    const deepThink = !!opts.deepThink;
    const sys = systemPrompt(s.intensity, puzzle, branches, projectMode, horrorSuspense);
    const userMsg = buildUserMessage(mode, ctx, opts.reviseNote, opts.directionNote, deepThink, branches, puzzle, projectMode, horrorSuspense);
    let messages;
    if (opts.resumeFrom && opts.redirectNote) {
      // 插话改方向：以已生成部分作为 assistant 上下文，把新指令作为 follow-up 续写（结构同自动续写）
      messages = [
        { role: 'system', content: sys },
        { role: 'user', content: userMsg },
        { role: 'assistant', content: opts.resumeFrom },
        { role: 'user', content: opts.redirectNote },
      ];
    } else {
      messages = [
        { role: 'system', content: sys },
        { role: 'user', content: userMsg },
      ];
    }
    if (opts.onStatus) opts.onStatus('AI 写作中');
    const genOpts = {
      stream: true,
      thinking: deepThink,
      onToken: opts.onToken,
      signal: opts.signal,
      onStatus: opts.onStatus,
    };
    let draft = await callDeepseek(messages, genOpts);
    draft = parseOutput(draft);
    // 自动续写补全：若被 max_tokens 截断（finish_reason==='length'，即“半截就没了”），
    // 在大纲/续写模式下带着已生成内容无缝接着写，最多补 2 次，直到自然收尾。
    let contTries = 0;
    while (genOpts._finishReason === 'length' && contTries < 2 && (mode === 'continue' || mode === 'generate' || mode === 'outline' || mode === 'expand' || mode === 'polish')) {
      contTries++;
      if (opts.onStatus) opts.onStatus('接续补全中 (' + contTries + ')');
      const contOpts = {
        stream: true,
        thinking: deepThink,
        onToken: opts.onToken,
        signal: opts.signal,
        onStatus: opts.onStatus,
      };
      const contMessages = [
        { role: 'system', content: sys },
        { role: 'user', content: userMsg },
        { role: 'assistant', content: draft },
        { role: 'user', content: '你上面的输出在结尾处因长度限制被截断了。请从被截断的位置无缝接着往下写，直到剧情到达一个自然的收束点（场景结束或留一个悬念钩子）再停。严禁重复已经写过的任何内容，也不要加任何开场白或说明，直接续上最后一个字继续输出剧本行。' },
      ];
      const more = parseOutput(await callDeepseek(contMessages, contOpts));
      if (!more.trim()) break;
      draft = (draft + '\n' + more).trim();
      genOpts._finishReason = contOpts._finishReason;
    }
    // 自检回路：默认关，仅勾选时跑（避免烧 token）
    if (s.selfCheck) {
      if (opts.onStatus) opts.onStatus('自检精修中');
      const reviewMsg = '你是导演，审一遍上面剧本的节奏、停顿、分割线、字号与排版（有无整段放大、相邻行跳动等过当处）及背景/音乐切换是否到位，只修正不到位处，仍输出原生格式：\n' + draft;
      const fixed = await callDeepseek(
        [{ role: 'system', content: sys }, { role: 'user', content: reviewMsg }],
        { stream: true, thinking: false, onToken: opts.onToken }
      );
      draft = parseOutput(fixed);
    }
    if (!draft.trim()) {
      throw new Error('AI 返回内容为空（可能被内容安全过滤、触发模型限流，或思考过程占满了输出）。请重试，或缩短「创作设定 / 已写前文」后重试。');
    }
    return draft;
  }

