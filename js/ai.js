  // 解析提取结果：拆出线索清单（==== 变更说明 ==== 之前）与变更说明（之后）
  function parseCluesOutput(raw) {
    if (!raw) return { clues: '', summary: '' };
    let t = String(raw).replace(/\r\n/g, '\n').trim();
    const fence = t.match(/^```(?:[a-zA-Z0-9_-]*)?\n?([\s\S]*?)```$/);
    if (fence) t = fence[1].trim();
    const m = t.split(/====\s*变更说明\s*====/);
    const clues = (m[0] || '').replace(/\n{2,}/g, '\n').trim();
    const summary = (m[1] || '').replace(/^[\s\-—–]+/, '').trim();
    return { clues, summary };
  }

