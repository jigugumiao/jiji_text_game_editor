  // ---------- 取真实素材名清单 ----------
  async function assetNameLists() {
    const out = { background: [], item: [], music: [], sound: [] };
    if (typeof window === 'undefined' || !window.Storage) return out;
    for (const lib of ['background', 'item', 'music', 'sound']) {
      try {
        const arr = await window.Storage.getAllAssets(lib);
        out[lib] = (arr || []).map(a => (a.name || '').trim()).filter(Boolean);
      } catch (e) { out[lib] = []; }
    }
    return out;
  }

  // ---------- 组装上下文（读 window.StoryEditorApi，便于在浏览器使用；node 测试可直传 ctx） ----------
  // ---------- 解析备注里的显式行数指令：仅当用户明确写了行数时才覆盖系统「至少3行」下限 ----------
  function lineCountDirective(note) {
    if (!note) return null;
    let n = null;
    const mGen = note.match(/生成\s*(\d+)\s*行/);          // 生成3行
    if (mGen) n = parseInt(mGen[1], 10);
    else if (/生成\s*一\s*行|只要\s*一\s*行|只\s*一\s*行|一\s*行\s*(就|即)/.test(note)) n = 1;  // 生成一行 / 一行即可
    else {
      const m = note.match(/(\d+)\s*行/);                 // 写3行 / 3行
      if (m) n = parseInt(m[1], 10);
    }
    if (!n || n < 1) return null;
    const verb = (n === 1) ? '恰好 1 行正文，绝不多写、绝不凑行数'
                            : ('约 ' + n + ' 行正文');
    return '\n\n【行数强制指令（覆盖系统下限）】你已在上方方向备注中明确要求生成 ' + n + ' 行——这推翻系统指令里“至少 3 行”的默认可选下限，你必须严格只输出' + verb + '，无视“至少 3 行”要求，也不要为凑篇幅多写。';
  }

  async function buildContext(mode) {
    const api = (typeof window !== 'undefined' && window.StoryEditorApi) || {};
    const full = api.getText ? api.getText() : '';
    const sel = api.getSel ? api.getSel() : { start: 0, end: full.length };
    const selStart = sel.start | 0;
    const selEnd = sel.end | 0;
    const hasSel = selEnd > selStart;
    const lines = full.split('\n');
    const caretLine = full.slice(0, selStart).split('\n').length; // 1-based（光标所在行）
    // 光标所在行属于「前文」（上文），「后文」（下文）从光标行之后算起
    // 上下文行数已是原 3 倍（前文 30→90，后文 10→30），让 AI 拿到更完整的剧情前后景
    const before = lines.slice(Math.max(0, caretLine - 90), caretLine).join('\n');
    const after = lines.slice(caretLine, caretLine + 30).join('\n');
    const selText = hasSel ? full.slice(selStart, selEnd) : '';
    const creation = api.getCreation ? api.getCreation() : {};
    const assets = await assetNameLists();
    return { full, selStart, selEnd, hasSel, selText, before, after, creation, assets, caretLine };
  }

